/* names.js — генерация названий города и кварталов из зерна. */
(function (global) {
  'use strict';
  const CM = (global.CM = global.CM || {});

  const PREFIX = ['Бел', 'Черн', 'Крас', 'Злат', 'Верх', 'Ниж', 'Стар', 'Нов', 'Тих', 'Даль',
    'Свет', 'Камен', 'Сол', 'Мор', 'Оз', 'Гор', 'Луг', 'Бор', 'Крут', 'Хлад', 'Яр', 'Вел'];
  const MIDDLE = ['о', 'о', 'о', 'е', 'а', 'и'];
  const ROOT = ['град', 'бор', 'горск', 'дол', 'мыс', 'кам', 'реч', 'стан', 'верь', 'мир',
    'холм', 'брод', 'ключ', 'вар', 'зор', 'кряж'];
  const SUFFIX = ['ск', 'ск', 'ов', 'ин', 'ополь', 'град', 'ое', 'ищи', 'ань'];

  const QUARTER_WORDS = {
    citadel: ['Цитадель', 'Детинец', 'Кремль', 'Верхний замок'],
    plaza: ['Соборная площадь', 'Ратушная площадь', 'Большая площадь'],
    oldtown: ['Старый город', 'Ремесленный конец', 'Кузнечная слобода', 'Гончарный квартал', 'Книжный конец'],
    market: ['Торговые ряды', 'Гостиный двор', 'Купеческий квартал', 'Ярмарочный конец'],
    temple: ['Храмовый квартал', 'Соборный конец', 'Монастырская слобода'],
    residential: ['Жилой квартал', 'Мещанская слобода', 'Садовый квартал', 'Тихий конец', 'Приречный квартал'],
    suburb: ['Окраина', 'Пригород', 'Дачная слобода', 'Заставный конец'],
    industrial: ['Промзона', 'Мануфактуры', 'Литейный двор', 'Складской конец', 'Лесопилки'],
    docks: ['Пристани', 'Портовый квартал', 'Рыбацкая слобода', 'Верфи'],
    park: ['Городской сад', 'Парк', 'Роща', 'Сквер', 'Ботанический сад'],
    farm: ['Поля', 'Огороды', 'Пашни', 'Хутора'],
    forest: ['Лес', 'Бор', 'Дубрава', 'Пуща'],
  };

  /** Название города по зерну. */
  CM.cityName = function (seed) {
    const rng = CM.rngFor(seed, 'name');
    let s = rng.pick(PREFIX);
    if (rng.bool(0.45)) s += rng.pick(MIDDLE) + rng.pick(ROOT);
    s += rng.pick(SUFFIX);
    // приводим к «Название» с заглавной буквы
    s = s.charAt(0).toUpperCase() + s.slice(1);
    if (rng.bool(0.12)) s = rng.pick(['Великий ', 'Нижний ', 'Верхний ', 'Новый ']) + s;
    return s;
  };

  /** Название квартала данного типа. */
  CM.quarterName = function (seed, i, j, type) {
    const list = QUARTER_WORDS[type] || ['Квартал'];
    const rng = CM.rngFor(seed, 'qname:' + i + ':' + j + ':' + type);
    return rng.pick(list);
  };

  CM.QUARTER_WORDS = QUARTER_WORDS;
})(window);
